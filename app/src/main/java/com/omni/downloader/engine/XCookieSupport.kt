package com.omni.downloader.engine

import android.content.Context
import android.util.Log
import com.omni.downloader.data.repository.SettingsRepository
import java.io.File

/**
 * X (Twitter) 登录凭证工具。
 *
 * 背景：X 对未登录游客返回 TweetTombstone（敏感内容 / 受保护推文），
 * 此时 yt-dlp 会报 “No video could be found in this tweet”。
 *
 * 注意：X 的 GraphQL 接口除了 Cookie 还要求 `x-csrf-token` 请求头，
 * 而 yt-dlp 只有在“Cookie 进入自己的 cookie jar”时才会自动写入该头
 * （见 yt_dlp/extractor/twitter.py 中 `_get_cookies(_API_BASE)['ct0']`）。
 * 因此这里把用户凭证落成 Netscape cookies.txt，通过 `--cookies` 交给引擎，
 * 而不是用 `--add-header Cookie:` 这种拿不到 csrf 头的方式。
 */
object XCookieSupport {

    private const val TAG = "XCookieSupport"
    private const val COOKIE_FILE_NAME = "x_cookies.txt"
    private const val COOKIE_TTL_SECONDS = 60L * 60 * 24 * 365 * 2
    private const val HEADER = "# Netscape HTTP Cookie File"
    private val COOKIE_DOMAINS = listOf(".x.com", ".twitter.com")

    /** 用户配置了凭证但内容不可用时抛出，便于在 UI 上给出明确提示。 */
    class InvalidCookieException(message: String) : Exception(message)

    @Volatile
    private var cachedSource: String? = null

    @Volatile
    private var cachedFile: File? = null

    /** 凭证变更后调用，强制下次重新写文件。 */
    fun invalidate() {
        cachedSource = null
        cachedFile = null
    }

    /**
     * 把当前保存的 X 凭证写成 yt-dlp 可用的 cookies.txt。
     *
     * @return 凭证文件；用户未配置凭证时返回 null（走游客身份，保持原有行为）。
     * @throws InvalidCookieException 配置了凭证但缺少 auth_token / ct0。
     */
    fun prepareCookieFile(context: Context): File? {
        val raw = SettingsRepository.getInstance(context).xCookie.value
        if (raw.isBlank()) return null

        val pairs = parseCookiePairs(raw)
        if (pairs.isEmpty()) {
            throw InvalidCookieException("X Cookie 格式无法识别，请粘贴 auth_token=xxx; ct0=xxx")
        }
        if (pairs["auth_token"].isNullOrBlank()) {
            throw InvalidCookieException("X Cookie 缺少 auth_token，请重新登录或粘贴完整 Cookie")
        }
        if (pairs["ct0"].isNullOrBlank()) {
            throw InvalidCookieException("X Cookie 缺少 ct0（X 强制要求 csrf 校验），请重新登录获取完整 Cookie")
        }

        val target = File(context.filesDir, COOKIE_FILE_NAME)
        cachedFile?.let { if (cachedSource == raw && it.exists()) return it }

        synchronized(this) {
            cachedFile?.let { if (cachedSource == raw && it.exists()) return it }

            val tmp = File(context.filesDir, "$COOKIE_FILE_NAME.tmp")
            tmp.writeText(buildNetscapeCookieText(pairs), Charsets.UTF_8)
            // 仅本应用可读，避免凭证被其他应用读取
            runCatching {
                tmp.setReadable(true, true)
                tmp.setWritable(true, true)
                tmp.setExecutable(false, false)
            }

            if (target.exists() && !target.delete()) {
                Log.w(TAG, "旧凭证文件删除失败，直接覆盖: ${target.absolutePath}")
            }
            if (!tmp.renameTo(target)) {
                target.writeText(buildNetscapeCookieText(pairs), Charsets.UTF_8)
                tmp.delete()
            }

            cachedSource = raw
            cachedFile = target
            return target
        }
    }

    /**
     * 解析 Cookie 字符串，兼容三种粘贴方式：
     * 1. `auth_token=xxx; ct0=yyy`
     * 2. 浏览器里复制出来的完整 Cookie（多个 `name=value;`）
     * 3. 直接粘贴的 Netscape cookies.txt 片段（制表符分隔）
     */
    fun parseCookiePairs(raw: String): Map<String, String> {
        val result = LinkedHashMap<String, String>()

        for (line in raw.lineSequence()) {
            val trimmed = line.trim()
            if (trimmed.isEmpty() || trimmed.startsWith("#")) continue

            if (trimmed.contains('\t')) {
                // Netscape 格式：domain \t flag \t path \t secure \t expiry \t name \t value
                val parts = trimmed.split('\t')
                if (parts.size >= 7) {
                    val name = parts[5].trim()
                    if (name.isNotEmpty()) result[name] = sanitizeValue(parts[6])
                }
                continue
            }

            for (pair in trimmed.split(';')) {
                val idx = pair.indexOf('=')
                if (idx <= 0) continue
                val name = pair.substring(0, idx).trim()
                if (name.isNotEmpty()) result[name] = sanitizeValue(pair.substring(idx + 1))
            }
        }

        // 只保留合法 token 名，避免把中文说明等脏数据写进 cookie 文件
        return result.filterKeys { it.matches(Regex("[A-Za-z0-9_.\\-]{1,64}")) }
    }

    private fun sanitizeValue(value: String): String {
        return value.trim().trim('"').filter { it != '\r' && it != '\n' && it != '\t' }
    }

    private fun buildNetscapeCookieText(pairs: Map<String, String>): String {
        val expiry = System.currentTimeMillis() / 1000 + COOKIE_TTL_SECONDS
        return buildString {
            appendLine(HEADER)
            appendLine("# Generated by OmniDownloader at ${System.currentTimeMillis()}")
            appendLine("# 域名 <TAB> 含子域 <TAB> 路径 <TAB> 仅HTTPS <TAB> 过期时间 <TAB> 名称 <TAB> 值")
            COOKIE_DOMAINS.forEach { domain ->
                pairs.forEach { (name, value) ->
                    append(domain)
                        .append('\t').append("TRUE")
                        .append('\t').append('/')
                        .append('\t').append("TRUE")
                        .append('\t').append(expiry)
                        .append('\t').append(name)
                        .append('\t').append(value)
                        .append('\n')
                }
            }
        }
    }

    /** 是否已配置可用的 X 凭证（仅做本地格式判断，不发起网络请求）。 */
    fun hasUsableCookie(cookie: String): Boolean {
        if (cookie.isBlank()) return false
        val pairs = parseCookiePairs(cookie)
        return !pairs["auth_token"].isNullOrBlank() && !pairs["ct0"].isNullOrBlank()
    }
}
